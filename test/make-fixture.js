// 產生匿名回歸測試用 fixture.xlsx（不含任何真實標案資料）。
// 只有需要「重建」fixture 時才跑： node test/make-fixture.js
// 平常跑 npm test 不需要它——test.js 直接讀已產好的 test/fixture.xlsx。
//
// 這份 fixture 是「黃金樣本」：每一列都是刻意設計、對應 test.js 內寫死的預期結果。
// 若你為了新需求改了 fixture，必須同步更新 test.js 的 golden 值，反之亦然。
const XLSX = require('xlsx');
const path = require('path');

const wb = XLSX.utils.book_new();

// ---- 範本格式（4 個固定工作表；欄序固定 A..H）----
// A序 B項次 C工項名稱 D原數量 E單位 F單價 G數量 H金額
const H = ['序','項次','工項名稱','原數量','單位','單價','數量','金額'];
XLSX.utils.book_append_sheet(wb, XLSX.utils.aoa_to_sheet([
  H,
  [1, 'B001', '混凝土',   10, 'M3', 2000,   3, 6000],   // 正常
  [2, 'B002', '鋼筋',     '', 'T',  50000, 0.5, 25000], // 原數量空白
  [3, 'B003', '級配',      5, 'M3', 1000,   4, 5000],   // 稽核警告：1000x4=4000≠5000
]), '原追加');
XLSX.utils.book_append_sheet(wb, XLSX.utils.aoa_to_sheet([
  H,
  [1, 'B010', '拆除',      '', '式', 0,    1, -8000],  // 式，不查稽核
  [2, 'B011', '回填',      20, 'M3', 300, -10, -3000],
]), '原追減');
XLSX.utils.book_append_sheet(wb, XLSX.utils.aoa_to_sheet([
  H,
  [1, 'N001', '新設標誌',  '', '面', 15000, 2, 30000],
]), '新增');
XLSX.utils.book_append_sheet(wb, XLSX.utils.aoa_to_sheet([
  H,
  [1, 'N010', '臨時設施',  '', '式', 0, 1, 50000],
]), '新增不議');

// ---- 概算書格式（明細表 v2 版型，對齊 skill budget_parser）----
// base=col B：B項次 C工項 D規格 E單位 F~H合約(數量/單價/金額) I~K變更(…) L~N增減(…)。
// 區塊標題「A.~E.」寫在 B 欄；區塊以 code 欄空白＋「計」列收尾。
// 金額欄（H/K/N）掛公式模擬真實預算書的公式鏈；K9 故意留手打常數＝
// 「脫離公式鏈」地雷（值 49000 也和實算 60×800=48000 不符 → 同列吃紅字）。
const est = [
  ['工程名稱：測試工程','','','','第2次變更'],
  ['','項次','工程項目','規格','單位','數量','單價','金額','數量','單價','金額','數量','單價','金額'],
  ['','A.原有項目無追加減部分'],
  ['','0110A','既有設施','','M',10,100,1000,10,100,1000,0,'',0],
  ['','','計'],
  ['','B.原有項目追加部分'],
  ['','0111','假設工程','','','','',190000,'','',229000,'','',39000],          // 大項（有子項）→ 不進金額鏈
  ['','0111A','排水溝','','M',100,1500,150000,120,1500,180000,20,'',30000],   // 乾淨
  ['','0111B','管溝','','M',50,800,40000,60,800,49000,10,'',9000],            // K9 手打且 ≠ 實算 48000
  ['','011','包工費小計','','','','','','','','','','',39000],
  ['','012','承商利潤及保險費','','','','','','','','','','',3900],
  ['','013','勞工安全衛生費用','','','','','','','','','','',1170],
  ['','014','品質管理費及材料檢驗費','','','','','','','','','','',780],
  ['','0B1','營業稅','','','','','','','','','','',4993],
  ['','','計'],
  ['','C.原有項目追減部分'],
  ['','0112A','移除舊管','','M',80,600,48000,65,600,39000,-15,'',-9000],      // 乾淨
  ['','0112B','舊柵欄','','M',30,200,6000,0,200,0,-30,'',-6000],              // 變更數量 0 → 全數追減句型
  ['','011','包工費小計','','','','','','','','','','',-15000],
  ['','','計'],
  ['','D.新增項目部分(需議價)'],
  ['','N301','新設柵欄','','M','','','',20,2500,50000,'','',''],              // 無 011 小計列 → 退回逐項加總
  ['','','計'],
  ['','E.新增項目部分(不議價)'],
  ['','N401','臨時設施','','式','','','',1,20000,20000,'','',''],
  ['','','計'],
];
const estWs = XLSX.utils.aoa_to_sheet(est);
// 金額欄公式（K9 故意不掛 → 手打常數）
const estF = {
  H4:'F4*G4', K4:'I4*J4', N4:'K4-H4',
  H7:'H8+H9', K7:'K8+K9', N7:'N8+N9',
  H8:'F8*G8', K8:'I8*J8', N8:'K8-H8',
  H9:'F9*G9',             N9:'K9-H9',
  N10:'N8+N9', N11:'N10*0.1', N12:'N10*0.03', N13:'N10*0.02',
  N14:'ROUND((N10+N11+N12+N13)*0.05,0)',
  H17:'F17*G17', K17:'I17*J17', N17:'K17-H17',
  H18:'F18*G18', K18:'I18*J18', N18:'K18-H18',
  N19:'N17+N18',
  K22:'I22*J22',
  K25:'I25*J25',
};
for (const a in estF) { if (estWs[a]) estWs[a].f = estF[a]; }
XLSX.utils.book_append_sheet(wb, estWs, '預算明細表');

const out = path.join(__dirname, 'fixture.xlsx');
XLSX.writeFile(wb, out);
console.log('已產生', out);
